package com.solthariel.pawchan

import com.solthariel.pawchan.core.ui.visiblePostSubject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class PostSubjectTest {
    @Test
    fun identicalSubjectAndBodyAreShownOnlyOnce() {
        val text = "Готовим ночную яишенку всем Двощом"
        assertNull(visiblePostSubject(text, text))
        assertNull(visiblePostSubject(" Title\n text ", "Title text"))
        assertNull(visiblePostSubject("Title\u00a0text", "Title text"))
    }

    @Test
    fun autogeneratedPrefixWithParagraphBreaksIsNotRepeated() {
        assertNull(visiblePostSubject("Первый абзац Второй", "Первый абзац\n\nВторой\nОстальной текст"))
    }

    @Test
    fun distinctSubjectIsKeptWithoutRemovingTheBody() {
        assertEquals("Heading", visiblePostSubject("Heading", "Body"))
        assertNull(visiblePostSubject("Heading", "Heading and more"))
        assertEquals("Head", visiblePostSubject("Head", "Heading and more"))
        assertEquals("Heading", visiblePostSubject("Heading", ""))
        assertNull(visiblePostSubject(" ", "Body"))
    }
}
